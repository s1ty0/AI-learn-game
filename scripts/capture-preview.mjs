import path from "node:path";
import { mkdir } from "node:fs/promises";
process.env.PLAYWRIGHT_BROWSERS_PATH = path.resolve(".runtime/browsers");
const { chromium } = await import("@playwright/test");
await mkdir(".runtime/screenshots", { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.goto("http://127.0.0.1:3000/workbench");
await page.locator(".react-flow__node").first().waitFor();
await page.getByRole("button", { name: "整理布局", exact: true }).click();
await page.getByRole("button", { name: "保存地图", exact: true }).click();
await page.getByRole("button", { name: "保存地图", exact: true }).waitFor({ state: "visible" });
await page.waitForFunction(() => document.querySelector(".graph-footer button")?.disabled);
await page.reload();
await page.locator(".react-flow__node").first().waitFor();
await page.waitForTimeout(400);
await page.screenshot({ path: ".runtime/screenshots/map.png", fullPage: true });
await page.getByRole("button", { name: "关卡实验", exact: true }).click();
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: ".runtime/screenshots/lab-clean.png", fullPage: true });
await browser.close();
console.log("Captured readable map and clean lab previews.");

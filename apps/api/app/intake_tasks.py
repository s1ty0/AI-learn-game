def task_at(answers):
    index = len(answers)
    if index >= 10:
        return None
    domain = index // 2
    variant = 0 if index % 2 == 0 else (2 if answers[-1]["outcome"] == "independent_choice" else 1)
    prompt, options, correct, hint, explanation = SPECS[domain][variant]
    return {"id": f"entry-{domain}-{variant}", "domain": DOMAINS[domain], "prompt": prompt,
            "options": options, "correct": correct, "hint": hint, "explanation": explanation,
            "kind": "操作直觉" if domain == 2 and variant == 1 else "选择探测"}
